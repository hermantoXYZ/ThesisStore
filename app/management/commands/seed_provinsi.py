class Command(BaseCommand):
    help = "Menginput data provinsi Indonesia"

    def handle(self, *args, **kwargs):
        data = [
            Provinsi(nama_provinsi=nama_provinsi)
            for nama_provinsi in PROVINSI_LIST
        ]

        Provinsi.objects.bulk_create(
            data,
            ignore_conflicts=True
        )

        self.stdout.write(
            self.style.SUCCESS("Data provinsi berhasil diproses.")
        )